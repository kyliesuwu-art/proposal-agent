def clone_selected_slides(source: Path, output: Path, selected: list[int]):
    """Package-level slide clone: change only presentation.xml's slide list.

    No shape is recreated and no source PPTX is opened for writing.  Orphaned
    relationships remain intentionally: PowerPoint ignores them, while every
    kept slide still points at its original media/theme/master package parts.
    """
    with zipfile.ZipFile(source) as zin:
        xml = zin.read("ppt/presentation.xml")
        from lxml import etree
        root = etree.fromstring(xml)
        ns = {"p": "http://schemas.openxmlformats.org/presentationml/2006/main"}
        ids = root.xpath("p:sldIdLst/p:sldId", namespaces=ns)
        if not all(1 <= n <= len(ids) for n in selected):
            raise ValueError(f"invalid source slide selection: {selected}")
        wanted = {ids[n - 1] for n in selected}
        for item in ids:
            if item not in wanted:
                item.getparent().remove(item)
        altered = etree.tostring(root, xml_declaration=True, encoding="UTF-8", standalone=True)
        selected_rel_ids = {item.get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id") for item in wanted}
        rels_root = etree.fromstring(zin.read("ppt/_rels/presentation.xml.rels"))
        for rel in list(rels_root):
            if rel.get("Type", "").endswith("/slide") and rel.get("Id") not in selected_rel_ids:
                rels_root.remove(rel)
        altered_rels = etree.tostring(rels_root, xml_declaration=True, encoding="UTF-8", standalone=True)
        output.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if item.filename == "ppt/presentation.xml":
                    zout.writestr(item, altered)
                elif item.filename == "ppt/_rels/presentation.xml.rels":
                    zout.writestr(item, altered_rels)
                else:
                    zout.writestr(item, zin.read(item.filename))


def write_text_preserving_style(shape, value: str):
    texts = list(shape._element.iter("{http://schemas.openxmlformats.org/drawingml/2006/main}t"))
    if not texts:
        return False
    texts[0].text = value
    for node in texts[1:]:
        node.text = ""
    return True


def replace_picture_media(deck: Path, slide_index: int, image: Path):
    """Replace a picture's media bytes while retaining its crop and geometry."""
    prs = Presentation(deck)
    pictures = [s for s in prs.slides[slide_index].shapes if shape_kind(s) == "picture"]
    if not pictures:
        return False
    picture = pictures[-1]  # never use a header logo as the test image slot
    rid = picture._element.blip_rId
    if not rid:
        return False
    media_name = str(picture.part.rels[rid].target_part.partname).lstrip("/")
    if Path(media_name).suffix.lower() != image.suffix.lower():
        return False
    with zipfile.ZipFile(deck) as zin:
        temp = deck.with_suffix(".tmp")
        with zipfile.ZipFile(temp, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                zout.writestr(item, image.read_bytes() if item.filename == media_name else zin.read(item.filename))
    temp.replace(deck)
    return True


def make_catalog():
    catalog_dir = OUT / "catalog"
    templates = OUT / "ppt_templates"
    previews = catalog_dir / "prototype_previews"
    catalog_dir.mkdir(parents=True, exist_ok=True)
    records = []
    for name, family, slide, use in PROTOTYPES:
        target = templates / f"{name.lower()}.pptx"
        clone_selected_slides(SOURCES[family], target, [slide])
        render_with_powerpoint(target, previews / name.lower())
        preview = next((previews / name.lower()).rglob("*.png"))
        record = {
            "prototype": name, "style_family": "COMKING_LIGHT_BLUE",
            "source_ppt": SOURCES[family].name, "source_key": family, "source_slide": slide,
            "preview": str(preview.relative_to(OUT)).replace("\\", "/"),
            "content_capacity": "title ≤ 2 lines; body follows the original slide's visible text regions",
            "slots": ["TITLE", "BODY", "IMAGE_MAIN"] if "IMAGE" in name or "SCREEN" in name else ["TITLE", "BODY"],
            "must_preserve": ["logo", "footer/header strip", "brand background", "decorative geometry", "original image crop frame"],
            "best_for": use,
        }
        records.append(record)
    (catalog_dir / "layout_catalog.json").write_text(json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")
    lines = ["# Template Library V1 — 真实页面原型目录", "", "所有原型均是从指定公司源 PPT 的真实 slide 做包级克隆；不是 python-pptx 重绘。", ""]
    for r in records:
        lines += [f"## {r['prototype']}", "", f"- 真实来源：`{r['source_key']}` 第 {r['source_slide']} 页（`{r['source_ppt']}`）",
                  f"- 适用表达：{r['best_for']}", f"- Slots：{', '.join(r['slots'])}",
                  f"- 保留资产：{', '.join(r['must_preserve'])}", f"- 预览：`{r['preview']}`", ""]
    (catalog_dir / "layout_catalog.md").write_text("\n".join(lines), encoding="utf-8")
    shutil.copy2(catalog_dir / "layout_catalog.json", OUT / "layout_catalog.json")
    shutil.copy2(catalog_dir / "layout_catalog.md", OUT / "layout_catalog.md")
    return records


