def shape_kind(shape):
    mapping = {
        MSO_SHAPE_TYPE.PICTURE: "picture",
        MSO_SHAPE_TYPE.TABLE: "table",
        MSO_SHAPE_TYPE.CHART: "chart",
        MSO_SHAPE_TYPE.GROUP: "group",
        MSO_SHAPE_TYPE.LINE: "line",
        MSO_SHAPE_TYPE.AUTO_SHAPE: "shape",
        MSO_SHAPE_TYPE.TEXT_BOX: "text_box",
        MSO_SHAPE_TYPE.PLACEHOLDER: "placeholder",
    }
    return mapping.get(shape.shape_type, str(shape.shape_type))


def walk_shapes(shapes, path=""):
    """Yield shapes including group children, with a stable source path."""
    for index, shape in enumerate(shapes):
        current = f"{path}/{index}" if path else str(index)
        yield current, shape
        if shape_kind(shape) == "group":
            yield from walk_shapes(shape.shapes, current)


def text_summary(shape):
    if not getattr(shape, "has_text_frame", False):
        return None
    text = " ".join(p.text.strip() for p in shape.text_frame.paragraphs if p.text.strip())
    if not text:
        return None
    fonts = []
    for paragraph in shape.text_frame.paragraphs:
        for run in paragraph.runs:
            if run.font.name:
                fonts.append(run.font.name)
    return {"text": text[:180], "font_names": sorted(set(fonts))}


def inventory(source: Path):
    prs = Presentation(source)
    fonts, kinds, slide_rows = Counter(), Counter(), []
    for idx, slide in enumerate(prs.slides, 1):
        row = {"slide": idx, "shapes": [], "counts": Counter(), "text_samples": []}
        for shape in slide.shapes:
            kind = shape_kind(shape)
            kinds[kind] += 1
            row["counts"][kind] += 1
            item = {"kind": kind, "name": shape.name, "x": shape.left, "y": shape.top,
                    "w": shape.width, "h": shape.height}
            text = text_summary(shape)
            if text:
                item.update(text)
                row["text_samples"].append(text["text"])
                fonts.update(text["font_names"])
            if kind == "picture":
                item["aspect_ratio"] = round(shape.width / shape.height, 3) if shape.height else None
            row["shapes"].append(item)
        row["counts"] = dict(row["counts"])
        slide_rows.append(row)
    theme = {"available": bool(getattr(prs, "slide_master", None)), "masters": len(prs.slide_masters),
             "layouts_per_master": [len(master.slide_layouts) for master in prs.slide_masters]}
    return {
        "source": source.name, "slide_count": len(prs.slides),
        "page_size_inches": {"width": round(prs.slide_width / 914400, 3), "height": round(prs.slide_height / 914400, 3)},
        "theme_and_master": theme, "font_frequency": fonts.most_common(20),
        "shape_frequency": kinds, "slides": slide_rows,
    }


def render_with_powerpoint(pptx: Path, target: Path):
    target.mkdir(parents=True, exist_ok=True)
    # SaveAs(18) does not reliably replace an existing same-name export folder.
    # This directory is generated by this experiment only, never a source deck.
    export_dir = target / "slide"
    if export_dir.exists():
        shutil.rmtree(export_dir)
    command = ["powershell", "-ExecutionPolicy", "Bypass", "-File", str(ROOT / "scripts" / "render_pptx_windows.ps1"),
               "-InputPath", str(pptx), "-OutputDir", str(target)]
    result = subprocess.run(command, cwd=ROOT, text=True, encoding="utf-8", errors="replace", capture_output=True, timeout=300)
    if result.returncode:
        raise RuntimeError(f"PowerPoint render failed for {pptx.name}: {result.stderr or result.stdout}")
    # PowerPoint SaveAs(18) creates a directory named after the requested
    # basename, then puts one PNG per slide inside it.
    return sorted((path for path in target.rglob("*") if path.suffix.lower() == ".png"), key=lambda p: p.name)


def contact_sheet(images, output: Path, cols=4, width=360):
    if not images:
        raise RuntimeError("No PowerPoint-rendered PNGs were produced")
    thumbs = []
    for path in images:
        with Image.open(path) as im:
            ratio = im.height / im.width
            thumb = im.convert("RGB").resize((width, round(width * ratio)))
            thumbs.append((path, thumb))
    cell_h = max(im.height for _, im in thumbs) + 32
    rows = (len(thumbs) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * width, rows * cell_h), "white")
    draw = ImageDraw.Draw(sheet)
    for i, (path, im) in enumerate(thumbs):
        x, y = (i % cols) * width, (i // cols) * cell_h
        sheet.paste(im, (x, y + 22))
        draw.text((x + 6, y + 4), path.name, fill="black")
    sheet.save(output)


def analysis_markdown(key, data):
    freq = data["shape_frequency"]
    image_slides = sum(1 for slide in data["slides"] if slide["counts"].get("picture"))
    return f"""# {key} 视觉审计

## 可验证的结构事实

- 页数：{data['slide_count']}；页面比例：{data['page_size_inches']['width']} × {data['page_size_inches']['height']} 英寸。
- 母版：{data['theme_and_master']['masters']} 个；每个母版布局数：{data['theme_and_master']['layouts_per_master']}。
- 页面对象统计：{dict(freq)}；含图片页面：{image_slides}/{data['slide_count']}。
- 可解析的字体出现频次：{data['font_frequency'][:12]}。主题、母版、图片裁切、透明度和阴影保留在原始 OOXML / 真实 PowerPoint 渲染中，不能仅以解析值替代视觉判断。

## 初步页面语言（以真实 contact sheet 复核）

- 封面、章节、图文、架构/流程和价值页均以真实页面截图为准标记；本实验不把解析出的形状统计误称为视觉结论。
- 标题、页脚、Logo、背景装饰、图片遮罩/裁切和配色是继承资产，prototype 内容替换时均不重画。
- 详见 `slide_inventory.json` 中每一页的文字样本、对象类型和矩形位置；后续 catalog 仅引用真实 slide 编号。
"""


def run_analysis():
    for key, source in SOURCES.items():
        if not source.exists():
            raise FileNotFoundError(source)
        directory = OUT / "source_analysis" / key
        directory.mkdir(parents=True, exist_ok=True)
        data = inventory(source)
        (directory / "slide_inventory.json").write_text(json.dumps(data, ensure_ascii=False, indent=2, default=dict), encoding="utf-8")
        (directory / "design_analysis.md").write_text(analysis_markdown(key, data), encoding="utf-8")
        pngs = render_with_powerpoint(source, directory / "slides")
        contact_sheet(pngs, directory / "contact_sheet.png")
        print(f"analysed {key}: {data['slide_count']} slides, {len(pngs)} PowerPoint PNGs")


