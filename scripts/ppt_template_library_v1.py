def execute_explicit_slot_map(*, map_name: str, values: dict[str, str], output_dir: Path) -> dict:
    """Strict probe writer: no shape discovery, no first-text/picture fallback."""
    map_path = OUT / "v2" / "slot_maps" / f"{map_name}.json"
    if not map_path.exists():
        raise RuntimeError(f"SLOT_MAP_MISSING:{map_name}")
    slot_map = json.loads(map_path.read_text(encoding="utf-8"))
    source = SOURCES["jiamusi"]
    deck = output_dir / "slide.pptx"
    clone_selected_slides(source, deck, [slot_map["source_slide"]])
    prs = Presentation(deck); slide = prs.slides[0]
    slots = slot_map["slots"]
    editable = {slot["shape_id"] for slot in slots if slot["editable"] and slot["type"] == "text"}
    preserved = {slot["shape_id"] for slot in slots if not slot["editable"]}
    trace = []
    for _, shape in walk_shapes(slide.shapes):
        if getattr(shape, "has_text_frame", False) and shape.shape_id not in editable | preserved:
            clear_shape_text(shape)
    for slot in slots:
        if slot["type"] != "text" or not slot["editable"]:
            continue
        value = values.get(slot["slot_id"], "")
        try:
            shape = target_shape_by_id(slide, slot["shape_id"])
            if len(value) > slot["max_chars"]:
                raise RuntimeError("CONTENT_TOO_LONG")
            write_text_preserving_style(shape, value)
            trace.append({"slot_id": slot["slot_id"], "target_shape_id": shape.shape_id, "target_shape_name": shape.name,
                          "content_written": value, "write_status": "PASS"})
        except KeyError:
            trace.append({"slot_id": slot["slot_id"], "target_shape_id": slot["shape_id"], "write_status": "SLOT_TARGET_NOT_FOUND"})
            raise RuntimeError(f"SLOT_TARGET_NOT_FOUND:{slot['slot_id']}")
    prs.save(deck)
    assets = ROOT / "outputs" / "ppt_style_v4" / "assets"
    for slot in slots:
        if slot["type"] != "picture":
            continue
        # Strict slot value only.  No first-picture/largest-picture fallback is
        # permitted in the Content Adapter path.
        replacement = values.get(slot["slot_id"])
        if not replacement:
            raise RuntimeError(f"IMAGE_CONTENT_MISSING:{slot['slot_id']}")
        asset = assets / replacement
        if not asset.exists():
            raise RuntimeError(f"IMAGE_ASSET_NOT_FOUND:{replacement}")
        result = replace_picture_slot(deck, 1, slot["shape_id"], asset)
        trace.append({"slot_id": slot["slot_id"], "target_shape_id": slot["shape_id"], "target_shape_name": "picture",
                      "content_written": replacement, "write_status": "PASS" if result["success"] else "IMAGE_SLOT_NOT_FOUND"})
        if not result["success"]:
            raise RuntimeError(f"IMAGE_SLOT_NOT_FOUND:{slot['slot_id']}")
    pngs = render_with_powerpoint(deck, output_dir / "rendered")
    shutil.copy2(pngs[0], output_dir / "slide.png")
    (output_dir / "slot_write_trace.json").write_text(json.dumps({"prototype": slot_map["prototype"], "SLOT_MAP_USED": True,
        "GENERIC_TEXTBOX_FALLBACK": False, "GENERIC_IMAGE_FALLBACK": False, "trace": trace}, ensure_ascii=False, indent=2), encoding="utf-8")
    return {"deck": deck, "trace": trace, "prototype": slot_map["prototype"]}


